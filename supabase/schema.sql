CREATE OR REPLACE FUNCTION public.log_activity()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_entity  text := tg_argv[0];
  v_old     jsonb;
  v_new     jsonb;
  v_row     jsonb;
  v_details jsonb := '{}'::jsonb;
  v_action  text;
  v_uid     uuid := auth.uid();
  v_name    text;
  v_role    text;
  i         int;
  c         text;
begin
  if tg_op <> 'INSERT' then v_old := to_jsonb(old); end if;
  if tg_op <> 'DELETE' then v_new := to_jsonb(new); end if;
  v_row := coalesce(v_new, v_old);

  for i in 1 .. tg_nargs - 1 loop
    c := tg_argv[i];
    if tg_op = 'UPDATE' then
      if (v_old -> c) is distinct from (v_new -> c) then
        v_details := v_details || jsonb_build_object(c, jsonb_build_object('from', v_old -> c, 'to', v_new -> c));
      end if;
    elsif coalesce(v_row -> c, 'null'::jsonb) <> 'null'::jsonb then
      v_details := v_details || jsonb_build_object(c, v_row -> c);
    end if;
  end loop;

  if tg_op = 'UPDATE' then
    if v_details = '{}'::jsonb then return null; end if;
    v_action := 'updated';
  elsif tg_op = 'INSERT' then
    v_action := 'created';
  else
    v_action := 'deleted';
  end if;

  if v_uid is not null then
    select full_name, role into v_name, v_role from profiles where id = v_uid;
  end if;

  insert into activity_log (actor_id, actor_name, actor_role, action, entity, entity_id, entity_name, details)
  values (
    v_uid,
    coalesce(v_name, case when v_uid is null then 'System' end),
    coalesce(v_role, case when v_uid is null then 'system' end),
    v_action,
    v_entity,
    v_row ->> 'id',
    coalesce(v_row ->> 'name', v_row ->> 'product_name', v_row ->> 'title',
             v_row ->> 'supplier_name', v_row ->> 'file_name'),
    v_details
  );
  return null;
exception when others then
  return null; -- never block the change itself
end;
$function$;

CREATE OR REPLACE FUNCTION public.log_receipt_restock()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_old       numeric;
  v_new       numeric;
  v_cost      numeric;
  v_ref       text;
  v_percent   numeric;
  v_suggested numeric;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    return new;
  end if;

  v_old  := nullif(to_jsonb(old)->>'quantity', '')::numeric;
  v_new  := nullif(to_jsonb(new)->>'quantity', '')::numeric;

  -- 1. the cost the scanner sent
  v_cost := new.last_cost;

  -- 2. the price it sent: a receipt's unit cost
  if v_cost is null and new.price is distinct from old.price and new.price > 0.01 then
    v_cost := new.price;
  end if;

  -- the cost is used once, then emptied
  new.last_cost := null;

  if v_new is null or v_old is null or v_new <= v_old then
    return new;
  end if;

  -- 3. the cost from this product's latest receipt
  if v_cost is null then
    select i.cost
      into v_cost
      from public.receipt_review_items i
     where i.product_id = to_jsonb(new)->>'id'
       and i.cost > 0.01
     order by i.created_at desc, i.id desc
     limit 1;
  end if;

  select upload_ref, percent
    into v_ref, v_percent
    from public.receipt_markups
   where created_at > now() - interval '15 minutes'
   order by created_at desc
   limit 1;

  if v_percent is not null and v_cost is not null and v_cost > 0.01 then
    v_suggested := round(v_cost * (1 + v_percent / 100), 2);
  else
    v_suggested := old.price;
  end if;

  insert into public.receipt_review_items
    (upload_ref, product_id, product_name, is_new, qty_added, cost, percent, price, stock_applied)
  values
    (v_ref,
     to_jsonb(new)->>'id',
     to_jsonb(new)->>'name',
     false,
     v_new - v_old,
     v_cost,
     v_percent,
     v_suggested,
     false);

  -- stock and price stay as they were until the owner confirms
  new.quantity := old.quantity;
  new.price := old.price;

  return new;
end;
$function$;

CREATE OR REPLACE FUNCTION public.log_stock_movement()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_query  text := lower(coalesce(current_query(), ''));
  v_old    integer := case when tg_op = 'INSERT' then 0 else coalesce(old.quantity, 0) end;
  v_reason text;
  v_by     text;
begin
  if tg_op = 'UPDATE' and new.quantity is not distinct from old.quantity then
    return new;
  end if;

  v_reason := case
    when v_query like '%admin_decide_refund%' or v_query like '%pos_refund%' then 'Refund'
    when v_query like '%staff_receive_delivery%' or v_query like '%receiving_apply%'
      or v_query like '%admin_approve_receiving%' then 'Delivery received'
    when v_query like '%admin_confirm_receipt_review%' then 'Receipt approved'
    when v_query like '%process_sale%'         then 'Sale'
    when v_query like '%add_stock%'            then 'Stock added'
    when v_query like '%set_product_quantity%' then 'Quantity edited'
    when v_query like '%approve_inspection%'   then 'Inspection return'
    when v_query like '%add_product%'          then 'New product'
    when coalesce(auth.role(), '') = 'service_role' then
      case when tg_op = 'INSERT' then 'New product (receipt, waiting for approval)' else 'Receipt scanner' end
    when tg_op = 'INSERT' then 'New product'
    else 'Other change'
  end;

  if auth.uid() is not null then
    select coalesce(nullif(trim(full_name), ''), email) into v_by
    from profiles
    where id = auth.uid();
  elsif coalesce(auth.role(), '') = 'service_role' then
    v_by := 'Receipt scanner (n8n)';
  else
    v_by := 'System';
  end if;

  insert into stock_movements (
    product_id, product_name, old_quantity, new_quantity, reason, changed_by, changed_by_name
  )
  values (
    new.id, new.name, v_old, coalesce(new.quantity, 0), v_reason, auth.uid(), v_by
  );

  return new;
end;
$function$;

