CREATE OR REPLACE FUNCTION public.receipt_supplier_of(p_ref text)
 RETURNS uuid
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  su   supplier_uploads%rowtype;
  v_id uuid;
begin
  if p_ref is null or p_ref !~ '^[0-9]+$' then
    return null;
  end if;

  select * into su from supplier_uploads where id = p_ref::bigint;
  if not found then
    return null;
  end if;

  -- uploaded by the supplier himself
  if exists (select 1 from profiles where id = su.supplier_id and role = 'supplier') then
    return su.supplier_id;
  end if;

  -- staff / owner upload: the supplier account with that name (only if one)
  if nullif(btrim(coalesce(su.supplier_name, '')), '') is not null then
    select min(p.id::text)::uuid into v_id
      from profiles p
     where p.role = 'supplier'
       and lower(btrim(p.full_name)) = lower(btrim(su.supplier_name))
    having count(*) = 1;
    return v_id;
  end if;

  return null;
end;
$function$;

CREATE OR REPLACE FUNCTION public.receiving_apply(p_delivery_id bigint)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  i        public.receipt_delivery_items%rowtype;
  r        public.receipt_review_items%rowtype;
  v_pieces integer := 0;
begin
  -- lets the guard above through: this is the delivery being received
  perform set_config('app.receiving', 'on', true);

  for i in select * from public.receipt_delivery_items where delivery_id = p_delivery_id order by id
  loop
    -- (stock_applied rows never join a delivery: their stock is in already)
    select * into r
      from public.receipt_review_items
     where id = i.review_item_id and status = 'pending' and not stock_applied
     for update;

    if not found then
      continue; -- already decided: nothing is added twice
    end if;

    if coalesce(i.received_qty, 0) > 0 and r.product_id is not null then
      update public.products
         set price = i.price,
             quantity = coalesce(quantity, 0) + i.received_qty
       where id::text = r.product_id;

      if not found then
        raise exception 'The product "%" no longer exists.', r.product_name;
      end if;

      update public.receipt_review_items
         set status = 'done',
             price = i.price,
             qty_added = i.received_qty,
             stock_applied = true,
             decision = 'approved',
             decided_at = now()
       where id = r.id;

      v_pieces := v_pieces + i.received_qty;
    else
      -- nothing of it arrived
      update public.receipt_review_items
         set status = 'done',
             decision = 'rejected',
             decided_at = now()
       where id = r.id;
    end if;
  end loop;

  update public.receipt_deliveries
     set stock_added_at = now(),
         added_pieces = v_pieces
   where id = p_delivery_id;

  perform set_config('app.receiving', '', true);
  return v_pieces;
end;
$function$;

