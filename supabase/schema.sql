CREATE OR REPLACE FUNCTION public.admin_confirm_receipt_review(p_items jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_item  jsonb;
  v_id    bigint;
  v_price numeric;
  r       public.receipt_review_items%rowtype;
begin
  if not public.is_admin() then
    raise exception 'Not authorized';
  end if;

  for v_item in select * from jsonb_array_elements(coalesce(p_items, '[]'::jsonb))
  loop
    v_id    := (v_item->>'id')::bigint;
    v_price := (v_item->>'price')::numeric;

    if v_price is null or v_price < 0 then
      raise exception 'Price must be 0 or more.';
    end if;

    -- lock the row so a double click can't add the stock twice
    select * into r
      from public.receipt_review_items
     where id = v_id and status = 'pending'
     for update;

    if not found or r.product_id is null then
      continue;
    end if;

    if r.stock_applied then
      -- rows from before this change: stock already added, only the price changes
      update public.products
         set price = v_price
       where id::text = r.product_id;
    else
      update public.products
         set price = v_price,
             quantity = coalesce(quantity, 0) + coalesce(r.qty_added, 0)::integer
       where id::text = r.product_id;

      if not found then
        raise exception 'The product "%" no longer exists.', r.product_name;
      end if;
    end if;

    update public.receipt_review_items
       set status = 'done',
           price = v_price,
           stock_applied = true,
           decision = case when r.stock_applied then decision else 'approved' end
     where id = v_id;
  end loop;
end;
$function$;

