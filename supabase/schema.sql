CREATE OR REPLACE FUNCTION public.raise_low_stock_notification()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_threshold integer := public.low_stock_threshold();
begin
  -- archived or deleted products aren't for sale, so nobody needs telling
  if coalesce(new.is_archived, false) or coalesce(new.is_deleted, false) then
    return new;
  end if;

  -- Only fire on the crossing: above the line before, at or below it now.
  -- Without this, every later sale of an already-low product would raise
  -- another alert and bury the bell.
  if coalesce(old.quantity, 0) > v_threshold
     and coalesce(new.quantity, 0) <= v_threshold then

    if coalesce(new.quantity, 0) = 0 then
      perform public.notify(
        'Out of Stock',
        format('%s is out of stock.', new.name),
        'low_stock',
        new.id
      );
    else
      perform public.notify(
        'Low Stock',
        format('%s is down to %s left (alert at %s).',
          new.name, new.quantity, v_threshold),
        'low_stock',
        new.id
      );
    end if;
  end if;

  return new;
end;
$function$;

