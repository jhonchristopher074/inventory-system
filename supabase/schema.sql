CREATE OR REPLACE FUNCTION public.update_my_name(p_full_name text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_profile profiles%rowtype;
begin
  perform public.require_auth();

  if p_full_name is null or trim(p_full_name) = '' then
    raise exception 'Name is required';
  end if;

  update profiles set full_name = trim(p_full_name)
  where id = auth.uid()
  returning * into v_profile;

  return to_jsonb(v_profile);
end;
$function$;

CREATE OR REPLACE FUNCTION public.update_product(p_product_id text, p_nickname text, p_price numeric, p_image_url text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if not public.is_admin() then
    raise exception 'Only an admin can edit products.';
  end if;

  if p_price is null or p_price < 0 then
    raise exception 'Price must be 0 or more.';
  end if;

  update public.products
     set nickname  = nullif(trim(coalesce(p_nickname, '')), ''),
         price     = p_price,
         image_url = nullif(trim(coalesce(p_image_url, '')), '')
   where id::text = p_product_id;

  if not found then
    raise exception 'Product not found.';
  end if;
end;
$function$;

