CREATE OR REPLACE FUNCTION public.add_product(p_name text, p_category text, p_quantity integer, p_price numeric, p_image_url text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_product products%rowtype;
begin
  perform public.require_role(array['admin']);

  if p_name is null or trim(p_name) = '' then
    raise exception 'Product name is required';
  end if;

  if coalesce(p_quantity, 0) < 0 then
    raise exception 'Quantity must be 0 or more.';
  end if;

  if coalesce(p_price, 0) < 0 then
    raise exception 'Price must be 0 or more.';
  end if;

  insert into products (
    name, category, quantity, price, image_url,
    is_archived, is_deleted, approved_count, return_count
  )
  values (
    trim(p_name),
    coalesce(nullif(trim(coalesce(p_category, '')), ''), 'Uncategorized'),
    coalesce(p_quantity, 0),
    coalesce(p_price, 0),
    nullif(trim(coalesce(p_image_url, '')), ''),
    false, false, 0, 0
  )
  returning * into v_product;

  perform public.notify(
    'Product Added',
    format('%s was added to inventory.', v_product.name),
    'restore',
    v_product.id
  );

  return to_jsonb(v_product);
end;
$function$;

CREATE OR REPLACE FUNCTION public.add_stock(p_product_id bigint, p_amount integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_product products%rowtype;
begin
  perform public.require_role(array['admin']);

  if p_amount is null or p_amount <= 0 then
    raise exception 'Stock amount must be greater than zero';
  end if;

  select * into v_product from products where id = p_product_id for update;

  if not found then
    raise exception 'Product % not found', p_product_id;
  end if;

  update products
  set quantity = quantity + p_amount
  where id = p_product_id
  returning * into v_product;

  perform public.notify(
    'Stock Added',
    format('%s stock added to %s.', p_amount, v_product.name),
    'restore',
    p_product_id
  );

  return to_jsonb(v_product);
end;
$function$;

