CREATE OR REPLACE FUNCTION public.disable_product(p_product_id bigint, p_reason text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_reason  text := btrim(coalesce(p_reason, ''));
  v_name    text;
  v_product text;
  v_id      bigint;
begin
  perform public.require_role(array['cashier', 'admin']);

  if length(v_reason) < 3 then
    raise exception 'Say why the product is disabled (at least 3 characters).';
  end if;
  if length(v_reason) > 200 then
    raise exception 'The reason is too long (200 characters at most).';
  end if;

  select coalesce(nullif(btrim(full_name), ''), email) into v_name
  from public.profiles where id = auth.uid();

  update public.products
     set is_disabled         = true,
         disabled_reason     = v_reason,
         disabled_at         = now(),
         disabled_by         = auth.uid(),
         disabled_by_name    = v_name,
         disabled_emailed_at = null
   where id = p_product_id
     and not is_disabled
     and not coalesce(is_archived, false)
     and not coalesce(is_deleted, false)
  returning name into v_product;

  if v_product is null then
    raise exception 'This product is already disabled, or no longer in the POS.';
  end if;

  v_id := public.notify(
    'Product Disabled',
    format('%s disabled "%s" at the POS: %s', coalesce(v_name, 'A cashier'), v_product, v_reason),
    'disabled',
    p_product_id
  );

  -- for the owner only (where notifications can be aimed at a role)
  if v_id is not null and exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'notifications' and column_name = 'recipient_role'
  ) then
    execute 'update public.notifications set recipient_role = $1 where id = $2' using 'admin', v_id;
  end if;
end;
$function$;

CREATE OR REPLACE FUNCTION public.document_inspection_approval(p_approval_id bigint)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  a public.inspection_approvals%rowtype;
  p public.products%rowtype;
  v_approved integer;
  v_return integer;
  v_result text;
begin
  select * into a from public.inspection_approvals where id = p_approval_id;

  if not found then
    raise exception 'Approval % not found.', p_approval_id;
  end if;

  if exists (select 1 from public.documentations where approval_id = a.id) then
    return; -- already documented
  end if;

  select * into p from public.products where id = a.product_id;

  v_approved := coalesce(a.approved_qty, 0);
  v_return   := coalesce(a.return_qty, 0);

  v_result := case
    when v_return = 0 then 'Approved'
    when v_approved = 0 then 'Return'
    else 'Approved with returns'
  end;

  insert into public.documentations (
    approval_id, type, title, description,
    product_id, product_name, receipt_image_url, image_url, created_by, created_by_id
  )
  values (
    a.id,
    'Inspection Document',
    'Inspection Result - ' || coalesce(a.product_name, p.name, 'Product'),
    format(
      E'%s was inspected and approved on %s.\nResult: %s\nApproved: %s\nReturn: %s\nTotal inspected: %s\nInspected by: %s\nCategory: %s',
      coalesce(a.product_name, p.name, 'Product'),
      to_char(now() at time zone 'Asia/Manila', 'FMMonth FMDD, YYYY'),
      v_result,
      v_approved,
      v_return,
      v_approved + v_return,
      coalesce(nullif(trim(a.requested_by), ''), 'Staff'),
      coalesce(nullif(trim(p.category), ''), 'Uncategorized')
    ),
    a.product_id,
    coalesce(a.product_name, p.name),
    p.image_url,   -- same column the older inspection documents use for the picture
    p.image_url,
    a.requested_by,
    a.requested_by_id
  );
end;
