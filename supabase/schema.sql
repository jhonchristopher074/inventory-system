  v_item     public.sale_items%rowtype;
  v_qty      integer;
  v_pending  integer;
  v_id       bigint;
  v_name     text;
  v_amount   numeric := 0;
  v_lines    text[] := '{}';
  v_rows     jsonb := '[]'::jsonb;
  v_pcs      integer;
begin
  perform public.require_role(array['cashier', 'admin']);

  select * into v_sale from public.sales where id = p_sale_id;
  if not found then
    raise exception 'Sale #% was not found.', p_sale_id;
  end if;
  if v_sale.cashier_id is distinct from auth.uid() and not public.is_admin() then
    raise exception 'Sale #% was made by another cashier: the owner can refund it.', p_sale_id;
  end if;

  -- only today's sales (the store's day, Philippine time)
  if (v_sale.created_at at time zone 'Asia/Manila')::date <> (now() at time zone 'Asia/Manila')::date then
    raise exception 'Only today''s sales can be refunded. Sale #% was on %.',
      p_sale_id, to_char(v_sale.created_at at time zone 'Asia/Manila', 'Mon DD');
  end if;

  for v_e in select value from jsonb_array_elements(coalesce(p_items, '[]'::jsonb))
  loop
    v_qty := coalesce(nullif(v_e->>'quantity', '')::numeric::integer, 0);
    continue when v_qty = 0;

    if v_qty < 0 then
      raise exception 'A refund quantity can''t be below 0.';
    end if;

    select * into v_item
      from public.sale_items
     where id = (v_e->>'sale_item_id')::bigint and sale_id = p_sale_id
     for update;

    if not found then
      raise exception 'That product isn''t part of sale #%.', p_sale_id;
    end if;

    -- already asked for, not decided yet
    select coalesce(sum(ri.quantity), 0) into v_pending
      from public.refund_request_items ri
      join public.refund_requests r on r.id = ri.request_id
     where ri.sale_item_id = v_item.id and r.status = 'pending';

    if v_qty > v_item.quantity - v_pending then
      raise exception 'Only % "%" can still be refunded from sale #%.',
        greatest(v_item.quantity - v_pending, 0), v_item.product_name, p_sale_id;
    end if;

    v_rows := v_rows || jsonb_build_object(
      'sale_item_id', v_item.id,
      'product_id', v_item.product_id,
      'product_name', v_item.product_name,
      'quantity', v_qty,
      'price', v_item.price,
      'amount', v_item.price * v_qty);
    v_amount := v_amount + v_item.price * v_qty;
    v_lines := v_lines || format('%s × %s', v_qty, v_item.product_name);
  end loop;

  if jsonb_array_length(v_rows) = 0 then
    raise exception 'Choose at least one product to refund.';
  end if;

  select coalesce(nullif(btrim(full_name), ''), email) into v_name from public.profiles where id = auth.uid();

  insert into public.refund_requests (sale_id, note, amount, requested_by, requested_by_name)
  values (p_sale_id, nullif(btrim(coalesce(p_note, '')), ''), v_amount, auth.uid(), v_name)
  returning id into v_id;

  insert into public.refund_request_items (request_id, sale_item_id, product_id, product_name, quantity, price, amount)
  select v_id, (e->>'sale_item_id')::bigint, (e->>'product_id')::bigint, e->>'product_name',
         (e->>'quantity')::integer, (e->>'price')::numeric, (e->>'amount')::numeric
    from jsonb_array_elements(v_rows) e;

  -- done at once: off the sale, back into stock
  v_pcs := public.refund_apply(v_id, v_name);

  -- the owner gets the details (not when he did it himself)
  if not public.is_admin() then
    insert into public.notifications (title, message, type, is_read, recipient_role)
    values (
      'Refund',
      format('%s refunded ₱%s from sale #%s: %s. %s pcs back in stock.%s',
        coalesce(v_name, 'A cashier'), to_char(v_amount, 'FM999,999,990.00'), p_sale_id,
        array_to_string(v_lines[1:3], ', ')
          || case when cardinality(v_lines) > 3 then format(' and %s more', cardinality(v_lines) - 3) else '' end,
        v_pcs,
        coalesce(' Why: ' || nullif(btrim(coalesce(p_note, '')), ''), '')),
      'refund', false, 'admin');
  end if;

  return jsonb_build_object('id', v_id, 'amount', v_amount, 'pieces', v_pcs);
end;
$function$;

CREATE OR REPLACE FUNCTION public.process_sale(p_cashier_id uuid, p_cashier_name text, p_cashier_email text, p_items jsonb)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_sale_id    bigint;
  v_total      numeric := 0;
  v_line       record;
  v_product    products%rowtype;
  v_subtotal   numeric;
  v_sale_items jsonb := '[]'::jsonb;
  v_name       text;
  v_email      text;
begin
  perform public.require_role(array['cashier', 'admin']);

  if p_cashier_id is distinct from auth.uid() then
    raise exception 'Cannot record a sale for another user';
  end if;

  -- p_cashier_name / p_cashier_email are ignored
  select coalesce(nullif(trim(full_name), ''), email), email
    into v_name, v_email
    from profiles
   where id = auth.uid();

  if p_items is null or jsonb_typeof(p_items) <> 'array' then
    raise exception 'Cart is empty';
  end if;

  if jsonb_array_length(p_items) = 0 then
    raise exception 'Cart is empty';
  end if;

  -- every line needs a product and a whole quantity of at least 1
  if exists (
    select 1
    from jsonb_array_elements(p_items) e
    where coalesce(e->>'product_id', '') !~ '^[0-9]{1,18}$'
       or coalesce(e->>'quantity', '') !~ '^[0-9]{1,9}$'
       or case when coalesce(e->>'quantity', '') ~ '^[0-9]{1,9}$'
               then (e->>'quantity')::integer <= 0
               else true end
  ) then
    raise exception 'Invalid quantity in cart';
  end if;

  -- one row per product (lines for the same product are added together),
  -- locked in id order so two sales can't deadlock
  for v_line in
    select (e->>'product_id')::bigint as product_id,
           sum((e->>'quantity')::integer)::integer as qty
    from jsonb_array_elements(p_items) e
    group by 1
    order by 1
  loop
    select * into v_product
    from products
    where id = v_line.product_id
      and is_archived = false
      and is_deleted = false
    for update;

    if not found then
      raise exception 'Product % not found or unavailable', v_line.product_id;
    end if;

    if v_product.quantity < v_line.qty then
      raise exception 'Insufficient stock for "%": requested %, available %',
        v_product.name, v_line.qty, v_product.quantity;
    end if;

    v_subtotal := v_product.price * v_line.qty;
    v_total := v_total + v_subtotal;

    v_sale_items := v_sale_items || jsonb_build_object(
      'product_id',   v_product.id,
      'product_name', v_product.name,
      'quantity',     v_line.qty,
      'price',        v_product.price,
      'subtotal',     v_subtotal
    );
  end loop;

  insert into sales (cashier_id, cashier_name, cashier_email, total_amount)
  values (p_cashier_id, v_name, v_email, v_total)
  returning id into v_sale_id;

  insert into sale_items (sale_id, product_id, product_name, quantity, price, subtotal)
  select
    v_sale_id,
    (elem->>'product_id')::bigint,
    elem->>'product_name',
    (elem->>'quantity')::integer,
    (elem->>'price')::numeric,
    (elem->>'subtotal')::numeric
  from jsonb_array_elements(v_sale_items) elem;

  -- stock deduction here is what fires the low-stock trigger
  update products p
  set quantity = p.quantity - (elem->>'quantity')::integer
  from jsonb_array_elements(v_sale_items) elem
  where p.id = (elem->>'product_id')::bigint;

  perform public.notify(
    'New Sale Completed',
    format('%s completed sale #%s worth ₱%s.',
      coalesce(v_name, 'A cashier'), v_sale_id,
      to_char(v_total, 'FM999,999,990.00')),
    'sale'
  );

  return jsonb_build_object(
    'id',            v_sale_id,
    'cashier_id',    p_cashier_id,
    'cashier_name',  v_name,
    'cashier_email', v_email,
    'total_amount',  v_total,
    'items',         v_sale_items
  );
end;
$function$;

CREATE OR REPLACE FUNCTION public.products_use_known_category()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
  v_name text;
begin
  if tg_op = 'UPDATE' then
    if new.category is not distinct from old.category then
      return new;
    end if;

    -- only the owner moves a product that already has a category
    -- (blank or "Uncategorized" = none yet: n8n may fill those in)
    if lower(coalesce(nullif(trim(old.category), ''), 'uncategorized')) <> 'uncategorized'
       and not public.is_admin() then
      new.category := old.category;
      return new;
    end if;
  end if;

  select c.name into v_name
    from categories c
   where lower(c.name) = lower(trim(coalesce(new.category, '')));

  new.category := coalesce(v_name, 'Uncategorized');
  return new;
end;
$function$;

