-- Builds supabase/schema.sql: the whole database structure, read from the
-- live project's catalog (read-only, no data). Run by scripts/schema-snapshot.mjs:
--   node scripts/schema-snapshot.mjs
-- Each row is one statement; ord puts them in an order that runs on an
-- empty project (tables, then functions, then defaults that call them ...).

with
pub as (select 'public'::regnamespace as ns),

ext as (
  select 10 as ord, e.extname::text as sub,
         format('CREATE EXTENSION IF NOT EXISTS %I WITH SCHEMA %I;', e.extname, n.nspname) as sql
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
   where e.extname not in ('plpgsql')
),

enums as (
  select 20, t.typname::text,
         format(E'DO $$ BEGIN\n  CREATE TYPE public.%I AS ENUM (%s);\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $$;',
                t.typname, string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder))
    from pg_type t join pg_enum e on e.enumtypid = t.oid, pub
   where t.typnamespace = pub.ns
   group by t.typname
),

composites as (
  select 21, t.typname::text,
         format(E'DO $$ BEGIN\n  CREATE TYPE public.%I AS (%s);\nEXCEPTION WHEN duplicate_object THEN NULL;\nEND $$;',
                t.typname,
                (select string_agg(format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod)), ', ' order by a.attnum)
                   from pg_attribute a where a.attrelid = t.typrelid and a.attnum > 0 and not a.attisdropped))
    from pg_type t join pg_class c on c.oid = t.typrelid, pub
   where t.typnamespace = pub.ns and t.typtype = 'c' and c.relkind = 'c'
),

seqs as (
  select 30, c.relname::text,
         format('CREATE SEQUENCE IF NOT EXISTS public.%I AS %s START WITH %s INCREMENT BY %s MINVALUE %s MAXVALUE %s CACHE %s%s;',
                c.relname, format_type(s.seqtypid, null), s.seqstart, s.seqincrement, s.seqmin, s.seqmax, s.seqcache,
                case when s.seqcycle then ' CYCLE' else '' end)
    from pg_class c join pg_sequence s on s.seqrelid = c.oid, pub
   where c.relnamespace = pub.ns and c.relkind = 'S'
     and not exists (select 1 from pg_depend d where d.objid = c.oid and d.deptype = 'i')
),

tabs as (
  select 40, c.relname::text,
         format(E'CREATE TABLE IF NOT EXISTS public.%I (\n%s\n);', c.relname,
           coalesce((select string_agg(
                       format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                         case a.attidentity when 'a' then ' GENERATED ALWAYS AS IDENTITY'
                                            when 'd' then ' GENERATED BY DEFAULT AS IDENTITY' else '' end,
                         case when a.attgenerated = 's'
                              then ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED' else '' end,
                         case when a.attnotnull then ' NOT NULL' else '' end),
                       E',\n' order by a.attnum)
                      from pg_attribute a
                      left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
                     where a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped), ''))
    from pg_class c, pub
   where c.relnamespace = pub.ns and c.relkind in ('r', 'p') and not c.relispartition
),

funcs as (
  select 50, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
         rtrim(pg_get_functiondef(p.oid), E'\n') || ';'
    from pg_proc p, pub
   where p.pronamespace = pub.ns and p.prokind in ('f', 'p')
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),

views as (
  select 55, lpad(c.oid::text, 12, '0'),
         case when c.relkind = 'm'
              then format(E'CREATE MATERIALIZED VIEW IF NOT EXISTS public.%I AS\n%s', c.relname, pg_get_viewdef(c.oid, true))
              else format(E'CREATE OR REPLACE VIEW public.%I%s AS\n%s', c.relname,
                          case when c.reloptions is not null then ' WITH (' || array_to_string(c.reloptions, ', ') || ')' else '' end,
                          pg_get_viewdef(c.oid, true))
         end
    from pg_class c, pub
   where c.relnamespace = pub.ns and c.relkind in ('v', 'm')
),

defaults as (
  select 60, c.relname || '.' || a.attname,
         format('ALTER TABLE ONLY public.%I ALTER COLUMN %I SET DEFAULT %s;', c.relname, a.attname, pg_get_expr(d.adbin, d.adrelid))
    from pg_attrdef d
    join pg_class c on c.oid = d.adrelid
    join pg_attribute a on a.attrelid = d.adrelid and a.attnum = d.adnum, pub
   where c.relnamespace = pub.ns and c.relkind in ('r', 'p') and a.attgenerated = ''
),

owned as (
  select 61, s.relname::text,
         format('ALTER SEQUENCE public.%I OWNED BY public.%I.%I;', s.relname, t.relname, a.attname)
    from pg_depend d
    join pg_class s on s.oid = d.objid and s.relkind = 'S'
    join pg_class t on t.oid = d.refobjid
    join pg_attribute a on a.attrelid = t.oid and a.attnum = d.refobjsubid, pub
   where d.deptype = 'a' and s.relnamespace = pub.ns
),

cons as (
  select case when con.contype = 'f' then 75 else 70 end, c.relname || '.' || con.conname,
         format('ALTER TABLE ONLY public.%I ADD CONSTRAINT %I %s;', c.relname, con.conname, pg_get_constraintdef(con.oid))
    from pg_constraint con join pg_class c on c.oid = con.conrelid, pub
   where c.relnamespace = pub.ns and con.contype in ('p', 'u', 'c', 'f', 'x') and con.conislocal
),

idx as (
  select 80, i.relname::text, pg_get_indexdef(i.oid) || ';'
    from pg_index x
    join pg_class i on i.oid = x.indexrelid
    join pg_class c on c.oid = x.indrelid, pub
   where c.relnamespace = pub.ns
     and not exists (select 1 from pg_constraint k where k.conindid = x.indexrelid and k.contype in ('p', 'u', 'x'))
),

trigs as (
  select 85, n.nspname || '.' || c.relname || '.' || t.tgname,
         pg_get_triggerdef(t.oid, true) || ';' ||
         case when t.tgenabled = 'D'
              then format(E'\nALTER TABLE %I.%I DISABLE TRIGGER %I;', n.nspname, c.relname, t.tgname) else '' end
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_proc p on p.oid = t.tgfoid, pub
   where not t.tgisinternal
     and (c.relnamespace = pub.ns or (n.nspname in ('auth', 'storage') and p.pronamespace = pub.ns))
),

rls as (
  select 90, c.relname::text,
         format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', c.relname) ||
         case when c.relforcerowsecurity then format(E'\nALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', c.relname) else '' end
    from pg_class c, pub
   where c.relnamespace = pub.ns and c.relkind in ('r', 'p') and c.relrowsecurity
),

pols as (
  select 91, n.nspname || '.' || c.relname || '.' || pol.polname,
         format(E'CREATE POLICY %I ON %I.%I AS %s FOR %s TO %s%s%s;', pol.polname, n.nspname, c.relname,
                case when pol.polpermissive then 'PERMISSIVE' else 'RESTRICTIVE' end,
                case pol.polcmd when 'r' then 'SELECT' when 'a' then 'INSERT' when 'w' then 'UPDATE' when 'd' then 'DELETE' else 'ALL' end,
                case when pol.polroles = '{0}' then 'public'
                     else (select string_agg(quote_ident(r.rolname), ', ') from pg_roles r where r.oid = any (pol.polroles)) end,
                coalesce(E'\n  USING (' || pg_get_expr(pol.polqual, pol.polrelid) || ')', ''),
                coalesce(E'\n  WITH CHECK (' || pg_get_expr(pol.polwithcheck, pol.polrelid) || ')', ''))
    from pg_policy pol
    join pg_class c on c.oid = pol.polrelid
    join pg_namespace n on n.oid = c.relnamespace
   where n.nspname in ('public', 'storage')
),

fgrants as (
  select 95, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
         format('REVOKE ALL ON FUNCTION public.%I(%s) FROM PUBLIC, anon, authenticated;', p.proname, pg_get_function_identity_arguments(p.oid)) ||
         coalesce(E'\n' || (select string_agg(format('GRANT EXECUTE ON FUNCTION public.%I(%s) TO %s;', p.proname,
                                                     pg_get_function_identity_arguments(p.oid),
                                                     case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end), E'\n' order by r.rolname)
                              from aclexplode(p.proacl) a left join pg_roles r on r.oid = a.grantee
                             where a.privilege_type = 'EXECUTE' and a.grantee <> p.proowner), '')
    from pg_proc p, pub
   where p.pronamespace = pub.ns and p.prokind in ('f', 'p') and p.proacl is not null
     and not exists (select 1 from pg_depend d where d.objid = p.oid and d.deptype = 'e')
),

tgrants as (
  select 96, c.relname::text,
         format('REVOKE ALL ON TABLE public.%I FROM anon, authenticated;', c.relname) ||
         coalesce(E'\n' || (select string_agg(format('GRANT %s ON TABLE public.%I TO %s;', g.privs, c.relname, g.who), E'\n' order by g.who)
                              from (select case when a.grantee = 0 then 'PUBLIC' else quote_ident(r.rolname) end as who,
                                           string_agg(a.privilege_type, ', ' order by a.privilege_type) as privs
                                      from aclexplode(c.relacl) a left join pg_roles r on r.oid = a.grantee
                                     where a.grantee <> c.relowner and coalesce(r.rolname, '') in ('', 'anon', 'authenticated', 'service_role')
                                     group by 1) g), '')
    from pg_class c, pub
   where c.relnamespace = pub.ns and c.relkind in ('r', 'p', 'v', 'm') and c.relacl is not null
),

comments as (
  select 97, 'table ' || c.relname, format('COMMENT ON TABLE public.%I IS %L;', c.relname, d.description)
    from pg_description d join pg_class c on c.oid = d.objoid and d.classoid = 'pg_class'::regclass and d.objsubid = 0, pub
   where c.relnamespace = pub.ns
  union all
  select 97, 'column ' || c.relname || '.' || a.attname, format('COMMENT ON COLUMN public.%I.%I IS %L;', c.relname, a.attname, d.description)
    from pg_description d
    join pg_class c on c.oid = d.objoid and d.classoid = 'pg_class'::regclass
    join pg_attribute a on a.attrelid = c.oid and a.attnum = d.objsubid, pub
   where c.relnamespace = pub.ns and d.objsubid > 0
  union all
  select 97, 'function ' || p.proname, format('COMMENT ON FUNCTION public.%I(%s) IS %L;', p.proname, pg_get_function_identity_arguments(p.oid), d.description)
    from pg_description d join pg_proc p on p.oid = d.objoid and d.classoid = 'pg_proc'::regclass, pub
   where p.pronamespace = pub.ns
),

realtime as (
  select 98, t.tablename::text, format('ALTER PUBLICATION supabase_realtime ADD TABLE public.%I;', t.tablename)
    from pg_publication_tables t
   where t.pubname = 'supabase_realtime' and t.schemaname = 'public'
),

buckets as (
  select 99, b.id,
         format('INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types) VALUES (%L, %L, %s, %s, %s) ON CONFLICT (id) DO NOTHING;',
                b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'NULL'),
                coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'NULL'))
    from storage.buckets b
)

select * from (
  select * from ext union all select * from enums union all select * from composites
  union all select * from seqs union all select * from tabs union all select * from funcs
  union all select * from views union all select * from defaults union all select * from owned
  union all select * from cons union all select * from idx union all select * from trigs
  union all select * from rls union all select * from pols union all select * from fgrants
  union all select * from tgrants union all select * from comments union all select * from realtime
  union all select * from buckets
) s
order by 1, 2;
